#!/usr/bin/env python3
"""M0.3: extract AlexNet layer-2 LPIPS weights into a C++ header.

Emits:
  assets/lpips_alex_l2.h          constexpr float arrays (conv1, conv2, lin2)
  tests/unit/lpips_alex_golden.h  golden (image pair, distance) test vectors

The reference computation here is LPIPS restricted to the SECOND AlexNet layer
(relu2), the AEROBLADE configuration: scaling([-1,1] -> ImageNet norm) ->
conv1+relu -> pool1 -> conv2+relu -> per-channel spatial unit-normalize ->
weighted squared difference, averaged over space.

Sources (downloaded once, cached by torchvision/urllib):
  torchvision alexnet (OWT): https://download.pytorch.org/models/alexnet-owt-7be5be79.pth
  LPIPS v0.1 alex calibration: PerceptualSimilarity/lpips/weights/v0.1/alex.pth

Run with the antidetect-eval venv python.
"""
import pathlib

import numpy as np
import torch
import torch.nn.functional as F

ROOT = pathlib.Path(__file__).resolve().parents[2]
LPIPS_ALEX_URL = (
    "https://raw.githubusercontent.com/richzhang/PerceptualSimilarity/"
    "master/lpips/weights/v0.1/alex.pth"
)
IMAGENET_MEAN = torch.tensor([0.485, 0.456, 0.406])
IMAGENET_STD = torch.tensor([0.229, 0.224, 0.225])


def load_weights():
    alex = torch.hub.load_state_dict_from_url(
        "https://download.pytorch.org/models/alexnet-owt-7be5be79.pth",
        map_location="cpu",
    )
    lp = torch.hub.load_state_dict_from_url(
        LPIPS_ALEX_URL, file_name="lpips_alex_v0.1.pth", map_location="cpu"
    )
    conv1_w, conv1_b = alex["features.0.weight"], alex["features.0.bias"]
    conv2_w, conv2_b = alex["features.3.weight"], alex["features.3.bias"]
    lin2_w = lp["lin1.model.1.weight"]  # relu2 <-> lin1 (0-based), 192 channels
    assert conv1_w.shape == (64, 3, 11, 11), conv1_w.shape
    assert conv2_w.shape == (192, 64, 5, 5), conv2_w.shape
    assert lin2_w.shape == (1, 192, 1, 1), lin2_w.shape
    return conv1_w, conv1_b, conv2_w, conv2_b, lin2_w.reshape(-1)


def lpips_l2_reference(a_u8_bgr, b_u8_bgr):
    """Layer-2-only LPIPS between two uint8 BGR images (the C++ TU's contract)."""
    a = torch.from_numpy(a_u8_bgr[:, :, ::-1].copy()).permute(2, 0, 1).float() / 255.0
    b = torch.from_numpy(b_u8_bgr[:, :, ::-1].copy()).permute(2, 0, 1).float() / 255.0

    def prep(x):
        x = x * 2.0 - 1.0  # [0,1] -> [-1,1]
        x = (x - IMAGENET_MEAN[:, None, None]) / IMAGENET_STD[:, None, None]
        x = x[None]
        h = F.conv2d(x, W1, B1, stride=4, padding=2)
        h = F.relu(h)
        h = F.max_pool2d(h, 3, 2)
        # torchvision alexnet conv2 has NO groups (the 2-GPU grouping of the
        # original paper did not survive into the reference weights).
        h = F.conv2d(h, W2, B2, stride=1, padding=2)
        h = F.relu(h)
        return h[0]

    def normchan(t):
        return t / t.square().sum(dim=(1, 2), keepdim=True).clamp_min(1e-8).sqrt()

    fa, fb = normchan(prep(a)), normchan(prep(b))
    d = (fa - fb).square() * LIN2[:, None, None]
    return d.sum(dim=0).mean().item()


def emit_header(conv1_w, conv1_b, conv2_w, conv2_b, lin2_w, out_path):
    def arr(name, tensor, per_line=6):
        def tok(v):
            s = f"{v:.7g}"
            # "0f" is an invalid literal: make every token a real float.
            if "." not in s and "e" not in s and "E" not in s:
                s += ".0"
            return s + "f"

        flat = tensor.reshape(-1).tolist()
        lines = [f"inline constexpr float {name}[] = {{"]
        for i in range(0, len(flat), per_line):
            lines.append("    " + ", ".join(tok(v) for v in flat[i : i + per_line]) + ",")
        lines.append("};")
        return "\n".join(lines), len(flat)

    parts = [
        "// Generated by experiments/antidetect-eval/extract_lpips_weights.py (M0.3).",
        "// AlexNet (torchvision OWT) conv1 + conv2 and the LPIPS v0.1 alex layer-2",
        "// calibration weights (relu2 <-> lin1). LPIPS is BSD-3",
        "// (richzhang/PerceptualSimilarity); torchvision OWT alexnet weights are",
        "// BSD-3.",
        "#pragma once",
        "",
        "namespace wmr::embedded {",
        "",
    ]
    total = 0
    for name, t in [
        ("kLpipsAlexConv1W", conv1_w),
        ("kLpipsAlexConv1B", conv1_b),
        ("kLpipsAlexConv2W", conv2_w),
        ("kLpipsAlexConv2B", conv2_b),
        ("kLpipsAlexLin2W", lin2_w),
    ]:
        text, n = arr(name, t)
        parts.append(text + "\n")
        parts.append(f"inline constexpr size_t k{name}Count = {n};\n")
        total += n
    parts.append("} // namespace wmr::embedded")
    out_path.write_text("\n".join(parts) + "\n")
    return total


def emit_golden(out_path):
    rng = np.random.default_rng(20260901)
    cases = []

    def grad(w, h, base, slope):
        img = np.zeros((h, w, 3), np.uint8)
        for x in range(w):
            img[:, x, 0] = np.clip(base[0] + slope[0] * x, 0, 255)
            img[:, x, 1] = np.clip(base[1] + slope[1] * x, 0, 255)
            img[:, x, 2] = np.clip(base[2] + slope[2] * x, 0, 255)
        return img

    pairs = [
        ("identical_gradient", grad(128, 96, (30, 60, 90), (4, 3, 2)),
         grad(128, 96, (30, 60, 90), (4, 3, 2))),
        ("gradient_vs_noisy", grad(128, 96, (30, 60, 90), (4, 3, 2)),
         np.clip(grad(128, 96, (30, 60, 90), (4, 3, 2)).astype(int)
                 + rng.integers(-12, 13, (96, 128, 3)), 0, 255).astype(np.uint8)),
        ("two_random", rng.integers(0, 256, (96, 128, 3)).astype(np.uint8),
         rng.integers(0, 256, (96, 128, 3)).astype(np.uint8)),
        ("flat_vs_slightly_flat", np.full((96, 128, 3), 120, np.uint8),
         np.full((96, 128, 3), 125, np.uint8)),
    ]
    lines = [
        "// Generated by experiments/antidetect-eval/extract_lpips_weights.py (M0.3).",
        "// Golden vectors for the layer-2 LPIPS port: uint8 BGR image pairs and",
        "// the reference distance computed with torch on this exact data.",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace wmr::embedded {",
        "",
        "struct LpipsGoldenPair {",
        "    const char* name;",
        "    int width, height;",
        "    const uint8_t* a_bgr;  // width*height*3",
        "    const uint8_t* b_bgr;",
        "    float expected;",
        "};",
        "",
    ]
    blobs = []
    for name, a, b in pairs:
        d = lpips_l2_reference(a, b)
        an, bn = f"gold_a_{name}", f"gold_b_{name}"
        for arr_name, img in ((an, a), (bn, b)):
            flat = img.reshape(-1).tolist()
            rows = []
            for i in range(0, len(flat), 24):
                rows.append("    " + ",".join(str(v) for v in flat[i : i + 24]) + ",")
            blobs.append(
                f"inline constexpr uint8_t {arr_name}[] = {{\n" + "\n".join(rows) + "\n};"
            )
        cases.append(
            f'    {{"{name}", {a.shape[1]}, {a.shape[0]}, {an}, {bn}, {d:.6f}f}},'
        )
        print(f"{name}: {d:.6f}")
    lines.extend(blobs)
    lines.append("")
    lines.append(f"inline constexpr LpipsGoldenPair kLpipsGoldenPairs[] = {{")
    lines.extend(cases)
    lines.append("};")
    lines.append(
        f"inline constexpr size_t kLpipsGoldenPairCount = {len(cases)};"
    )
    lines.append("} // namespace wmr::embedded")
    out_path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    w1, b1, w2, b2, lin = load_weights()
    globals().update(W1=w1, B1=b1, W2=w2, B2=b2, LIN2=lin)
    n = emit_header(w1, b1, w2, b2, lin, ROOT / "assets" / "lpips_alex_l2.h")
    print(f"wrote assets/lpips_alex_l2.h ({n} floats)")
    emit_golden(ROOT / "tests" / "unit" / "lpips_alex_golden.h")
    print("wrote tests/unit/lpips_alex_golden.h")
